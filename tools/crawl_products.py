    log("== downloading banners ...")
    import hashlib
    banners = []
    for url in banner_urls[:4]:
        ext = ext_of(url)
        filename = "banner_%s%s" % (hashlib.md5(url.encode()).hexdigest()[:8], ext)
        dest = os.path.join(IMG_BANNER, filename)
        if not os.path.exists(dest):
            try:
                size = download_image(url, dest)
                log("  %-28s %7d bytes" % (filename, size))
            except Exception as e:
                log("  [warn] banner failed %s: %r" % (filename, e))
                continue
