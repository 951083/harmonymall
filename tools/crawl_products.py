def log(msg):
    print(msg, flush=True)


def http_get(url, as_json=True, retry=2):
    for attempt in range(retry):
        try:
            req = urllib.request.Request(url, headers={
                "User-Agent": UA,
                "Accept": "application/json,text/html,*/*",
                "Referer": "https://you.163.com/",
            })
            with urllib.request.urlopen(req, timeout=20, context=CTX) as resp:
                raw = resp.read()
            return json.loads(raw.decode("utf-8")) if as_json else raw
        except Exception as e:
            if attempt == retry - 1:
                raise
            time.sleep(1.0)


def ext_of(url):
    m = re.search(r"\.(png|jpg|jpeg|webp)(?:\?|$)", url, re.I)
    return "." + (m.group(1).lower() if m else "png")


def download_image(url, dest):
    req = urllib.request.Request(url, headers={
        "User-Agent": UA,
        "Referer": "https://you.163.com/",
    })
    with urllib.request.urlopen(req, timeout=30, context=CTX) as resp:
        data = resp.read()
    if len(data) < 1024:
        raise ValueError("image too small: " + url)
    with open(dest, "wb") as f:
        f.write(data)
    return len(data)


def clean_name(name):
    name = re.sub(r"^【[^】]*】", "", name or "").strip()
    name = re.sub(r"\s+", " ", name)
    return name[:90]


def esc(s):
    return (s or "").replace("'", "''")


def fetch_keyword(keyword):
    url = ("https://you.163.com/xhr/search/search.json?keyword="
           + urllib.parse.quote(keyword)
           + "&page=1&sortType=0&descSorted=false&categoryId=0&matchType=0")
    items = []
    category_hits = []
    for attempt in range(2):
        data = http_get(url)
        directly = (data or {}).get("data", {}).get("directly", {})
        result = directly.get("searcherResult", {}) or {}
        items = result.get("result", []) or []
        category_hits = directly.get("searcherCategoryHitCountList", []) or []
        if items:
            break
        time.sleep(1.5)
    return items, category_hits


def sku_specs(sku):
    specs = {}
    for pair in sku.get("itemSkuSpecValueList", []) or []:
        spec = pair.get("skuSpec") or {}
        value = pair.get("skuSpecValue") or {}
        if spec.get("name") and value.get("value"):
            specs[spec["name"]] = value["value"]
    return specs


