    products = []
    seen = set()
    banner_urls = []

    log("== crawling yanxuan ...")
    for keyword, category_id in KEYWORDS:
        try:
            items, category_hits = fetch_keyword(keyword)
        except Exception as e:
            log("  [warn] keyword %s failed: %r" % (keyword, e))
            continue
        for cat in category_hits:
            vo = cat.get("categoryVO") or {}
            b = vo.get("bannerUrl")
            if b and b not in banner_urls:
                banner_urls.append(b)
        taken = 0
        for item in items:
            if taken >= MAX_PER_KEYWORD or len(products) >= MAX_TOTAL:
                break
            if item.get("soldOut") or item.get("underShelf"):
                continue
            item_id = item.get("id")
            if not item_id or item_id in seen:
                continue
            price = item.get("retailPrice")
            if not price or price <= 0:
                continue
            name = clean_name(item.get("name"))
            if not name:
                continue
            seen.add(item_id)
            products.append({
                "id": item_id,
                "seq": len(products) + 1,
                "name": name,
                "desc": (item.get("simpleDesc") or "").strip(),
                "price_yuan": float(price),
                "counter_yuan": float(item.get("counterPrice") or 0),
                "image_url": item.get("listPicUrl") or item.get("primaryPicUrl"),
                "category_id": category_id,
                "skus": item.get("skuList") or [],
            })
            taken += 1
        log("  keyword %-8s -> %d items (total %d)" % (keyword, taken, len(products)))
        time.sleep(0.4)

    if not products:
        log("no products crawled, abort")
        return

    # 下载商品图（按商品 ID 命名，重复执行时自动覆盖同一商品，不会错位）
    log("== downloading product images ...")
    for p in products:
        ext = ext_of(p["image_url"])
        filename = "item_%d%s" % (p["id"], ext)
        dest = os.path.join(IMG_PRODUCTS, filename)
        if not os.path.exists(dest):
            try:
                size = download_image(p["image_url"], dest)
                log("  %-24s %7d bytes  %s" % (filename, size, p["name"][:30]))
            except Exception as e:
                log("  [warn] image failed %s: %r" % (filename, e))
                filename = ""
        else:
            log("  %-24s cached" % filename)
        p["image"] = "/img/products/" + filename if filename else ""
        time.sleep(0.15)

